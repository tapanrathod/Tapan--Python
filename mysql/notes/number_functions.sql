****************************************************************************************/

/*
1. ABS()
*/
 /*
SELECT ABS(-150);
*/

/*
Result:
150
*/


/*
2. ROUND()
*/
 /*
SELECT ROUND(123.456, 2);
*/

/*
Result:
123.46
*/


/*
3. CEILING() / FLOOR()
*/
 /*
SELECT CEILING(12.1), FLOOR(12.9);
*/

/*
Result:
13 | 12
*/


/*
4. MOD()
*/
 /*
SELECT MOD(10, 3);
*/

/*
Result:
1
*/


/*
5. POWER()
*/
 /*
SELECT POWER(2, 4);
*/

/*
Result:
16
*/


/*
6. SQRT()
*/
 /*
